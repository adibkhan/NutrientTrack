// Writes scripts/brand/pip.mjs from the app's own Pip drawing, so icons and the share image never drift from the diary.
//   SHEET_OUT=/tmp/sheet npx vite build --config scripts/brand/vite.sheet.config.ts
//   node scripts/brand/export-pip.mjs /tmp/sheet
// Resolves every CSS variable and gradient stop to a literal colour (light theme) and strips animation classes.
import { chromium } from 'playwright'
import { createServer } from 'node:http'
import { readFile, writeFile } from 'node:fs/promises'
import { extname, join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const [dist] = process.argv.slice(2)
const here = dirname(fileURLToPath(import.meta.url))
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.woff2': 'font/woff2' }
const server = createServer(async (request, response) => {
  const path = request.url.split('?')[0] === '/' ? '/index.html' : request.url.split('?')[0]
  let body
  try { body = await readFile(join(dist, path)) } catch { response.writeHead(404).end(); return }
  response.writeHead(200, { 'content-type': types[extname(path)] ?? 'application/octet-stream' }).end(body)
}).listen(0)
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM ?? undefined })
const page = await browser.newPage()
await page.goto(`http://localhost:${server.address().port}/?export=1&theme=light`)
await page.waitForSelector('.pip')
const variants = await page.evaluate(() => {
  const out = {}
  const PROPS = ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'opacity', 'stop-color', 'stop-opacity', 'font-size', 'font-weight', 'font-family']
  for (const holder of document.querySelectorAll('[data-variant]')) {
    const svg = holder.querySelector('svg')
    const clone = svg.cloneNode(true)
    const originals = [svg, ...svg.querySelectorAll('*')]
    const clones = [clone, ...clone.querySelectorAll('*')]
    clones.forEach((node, index) => {
      const computed = getComputedStyle(originals[index])
      for (const prop of PROPS) {
        const value = computed.getPropertyValue(prop)
        if (value && value !== 'none' || prop === 'fill' && value === 'none') node.setAttribute(prop, value)
      }
      node.removeAttribute('style')
      node.removeAttribute('class')
      if (computed.display === 'none') node.remove()
    })
    clone.removeAttribute('class')
    clone.setAttribute('xmlns', 'http://www.w3.org/2000/svg')
    // Gradient ids come from React's useId; make them stable per variant.
    let html = clone.outerHTML.replace(/\s(width|height)="[^"]*"/g, '')
    const ids = [...new Set([...html.matchAll(/id="([^"]+)"/g)].map((m) => m[1]))]
    ids.forEach((id, index) => { html = html.split(id).join(`${holder.dataset.variant}-${index}`) })
    out[holder.dataset.variant] = html
  }
  return out
})
await browser.close()
server.close()
const body = `// Generated by scripts/brand/export-pip.mjs from src/components/Mascot.tsx. Do not edit by hand.
// Pip as static SVG markup with literal colours (light theme), for icons and share images.
const VARIANTS = ${JSON.stringify(variants, null, 2)}

export const pip = (size, { mood = 'happy', flower = true } = {}) => {
  const key = mood === 'wave' ? (flower ? 'wave-flower' : 'wave-plain') : mood === 'cheer' ? 'cheer-flower' : 'happy-flower'
  return VARIANTS[key].replace('<svg ', \`<svg width="\${size}" height="\${(size * 96) / 80}" \`)
}
`
await writeFile(join(here, 'pip.mjs'), body)
console.log(`Wrote pip.mjs with ${Object.keys(variants).length} variants`)
